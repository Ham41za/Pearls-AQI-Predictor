def detect_outliers_iqr(df, columns):

    results = []

    for column in columns:

        if column not in df.columns:
            continue

        data = df[column].dropna()

        Q1 = data.quantile(0.25)
        Q3 = data.quantile(0.75)

        IQR = Q3 - Q1

        lower = Q1 - 1.5 * IQR
        upper = Q3 + 1.5 * IQR

        outliers = data[
            (data < lower) |
            (data > upper)
        ]

        results.append({
            "Feature": column,
            "Q1": Q1,
            "Q3": Q3,
            "Lower Bound": lower,
            "Upper Bound": upper,
            "Outliers": len(outliers)
        })

    return pd.DataFrame(results)


