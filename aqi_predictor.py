# 10. SHAP ANALYSIS FUNCTION
# ================================================================

def run_shap_analysis(
    horizon,
    model_path,
    data,
    features,
    max_samples=300
):

    print("\n")
    print("=" * 70)
    print(
        f"SHAP ANALYSIS — {horizon}-HOUR FORECAST"
    )
    print("=" * 70)


    # ------------------------------------------------------------
    # Load model
    # ------------------------------------------------------------

    model = joblib.load(
        model_path
    )

    print("\nModel loaded successfully.")

    print(
        "Model type:",
        type(model).__name__
    )


    # ------------------------------------------------------------
    # Prepare data
    # ------------------------------------------------------------

    target_column = (
        f"target_AQI_{horizon}h"
    )

    required_columns = (
        features +
        [target_column]
    )

    temp_df = data[
        required_columns
    ].dropna().copy()


    if len(temp_df) == 0:

        print(
            "No valid rows available for SHAP analysis."
        )

        return None


    # ------------------------------------------------------------
    # Use a manageable sample
    # ------------------------------------------------------------

    if len(temp_df) > max_samples:

        shap_df = temp_df.tail(
            max_samples
        ).copy()

    else:

        shap_df = temp_df.copy()


    X_shap = shap_df[
        features
    ]


    print(
        "\nRows used for SHAP:",
        len(X_shap)
    )

    print(
        "Number of features:",
        len(features)
    )


    # ------------------------------------------------------------
    # Create SHAP Tree Explainer
    # ------------------------------------------------------------

    print(
        "\nCreating SHAP TreeExplainer..."
    )

    explainer = shap.TreeExplainer(
        model
    )


    # ------------------------------------------------------------
    # Calculate SHAP values
    # ------------------------------------------------------------

    print(
        "Calculating SHAP values..."
    )

    shap_values = explainer.shap_values(
        X_shap
    )


    # ------------------------------------------------------------
    # Handle SHAP output format
    # ------------------------------------------------------------

    if isinstance(
        shap_values,
        list
    ):

        shap_values_array = np.asarray(
            shap_values[0]
        )

    else:

        shap_values_array = np.asarray(
            shap_values
        )


    # Some SHAP versions can return
    # an additional output dimension.
    # For this regression model, select it safely.

    if shap_values_array.ndim == 3:

        shap_values_array = (
            shap_values_array[:, :, 0]
        )


    print(
        "SHAP values calculated."
    )

    print(
        "SHAP matrix shape:",
        shap_values_array.shape
    )


    # ============================================================
    # GLOBAL FEATURE IMPORTANCE
    # ============================================================

    mean_abs_shap = np.mean(
        np.abs(
            shap_values_array
        ),
        axis=0
    )


    importance_df = pd.DataFrame({

        "Feature": features,

        "Mean_Absolute_SHAP":
            mean_abs_shap

    })


    importance_df = (
        importance_df
        .sort_values(
            "Mean_Absolute_SHAP",
            ascending=False
        )
        .reset_index(drop=True)
    )


    # ------------------------------------------------------------
    # Save feature importance
    # ------------------------------------------------------------

    importance_file = (
        f"{SHAP_DIR}/"
        f"shap_importance_{horizon}h.csv"
    )

    importance_df.to_csv(
        importance_file,
        index=False
    )


    print("\n")
    print(
        f"TOP FEATURES — {horizon}H"
    )

    print("-" * 50)

    display(
        importance_df.head(15)
    )


    # ============================================================
    # BAR PLOT
    # ============================================================

    plt.figure(
        figsize=(10, 7)
    )

    top_n = min(
        15,
        len(importance_df)
    )

    top_data = (
        importance_df
        .head(top_n)
        .sort_values(
            "Mean_Absolute_SHAP"
        )
    )

    plt.barh(
        top_data["Feature"],
        top_data["Mean_Absolute_SHAP"]
    )

    plt.xlabel(
        "Mean Absolute SHAP Value"
    )

    plt.ylabel(
        "Feature"
    )

    plt.title(
        f"SHAP Feature Importance — "
        f"{horizon}-Hour AQI Forecast"
    )

    plt.tight_layout()

    bar_file = (
        f"{SHAP_DIR}/"
        f"shap_bar_{horizon}h.png"
    )

    plt.savefig(
        bar_file,
        dpi=150,
        bbox_inches="tight"
    )

    plt.show()


    # ============================================================
    # SHAP SUMMARY / BEESWARM PLOT
    # ============================================================

    print(
        f"\nGenerating SHAP summary plot..."
    )

    shap.summary_plot(
        shap_values_array,
        X_shap,
        show=True
    )


    # Save summary plot

    plt.savefig(
        f"{SHAP_DIR}/"
        f"shap_summary_{horizon}h.png",
        dpi=150,
        bbox_inches="tight"
    )

    plt.close()


    # ============================================================
    # INDIVIDUAL PREDICTION EXPLANATION
    # ============================================================

    print("\n")
    print("=" * 70)
    print(
        f"INDIVIDUAL PREDICTION — {horizon}H"
    )
    print("=" * 70)


    # Use latest available observation

    sample_index = len(X_shap) - 1

    sample = X_shap.iloc[
        sample_index
    ]


    # Model prediction

    prediction = model.predict(
        sample.to_frame().T
    )[0]


    # Actual value

    actual = shap_df[
        target_column
    ].iloc[
        sample_index
    ]


    print(
        "\nActual AQI:",
        actual
    )

    print(
        "Predicted AQI:",
        round(
            prediction,
            4
        )
    )

    print(
        "Prediction error:",
        round(
            abs(
                actual -
                prediction
            ),
            4
        )
    )


    # ------------------------------------------------------------
    # SHAP contribution for this observation
    # ------------------------------------------------------------

    individual_values = (
        shap_values_array[
            sample_index
        ]
    )


    individual_df = pd.DataFrame({

        "Feature":
            features,

        "Feature_Value":
            sample.values,

        "SHAP_Value":
            individual_values

    })


    individual_df[
        "Absolute_SHAP"
    ] = np.abs(
        individual_df[
            "SHAP_Value"
        ]
    )


    individual_df = (
        individual_df
        .sort_values(
            "Absolute_SHAP",
            ascending=False
        )
        .reset_index(drop=True)
    )


    print(
        "\nTop factors influencing this prediction:"
    )

    display(
        individual_df.head(10)
    )


    # ============================================================
    # INDIVIDUAL SHAP BAR PLOT
    # ============================================================

    individual_plot = (
        individual_df
        .head(10)
        .sort_values(
            "SHAP_Value"
        )
    )


    plt.figure(
        figsize=(10, 6)
    )

    plt.barh(
        individual_plot["Feature"],
        individual_plot["SHAP_Value"]
    )

    plt.axvline(
        0,
        linewidth=1
    )

    plt.xlabel(
        "SHAP Value"
    )

    plt.ylabel(
        "Feature"
    )

    plt.title(
        f"Prediction Explanation — "
        f"{horizon}-Hour Forecast"
    )

    plt.tight_layout()

    individual_file = (
        f"{SHAP_DIR}/"
        f"shap_individual_{horizon}h.png"
    )

    plt.savefig(
        individual_file,
        dpi=150,
        bbox_inches="tight"
    )

    plt.show()


    # ============================================================
    # SAVE INDIVIDUAL EXPLANATION
    # ============================================================

    individual_csv = (
        f"{SHAP_DIR}/"
        f"shap_individual_{horizon}h.csv"
    )

    individual_df.to_csv(
        individual_csv,
        index=False
    )


    # ============================================================
    # RETURN RESULTS
    # ============================================================

    return {
        "horizon": horizon,
        "model": model,
        "explainer": explainer,
        "X": X_shap,
        "shap_values": shap_values_array,
        "importance": importance_df,
        "individual": individual_df,
        "prediction": prediction,
        "actual": actual
    }


