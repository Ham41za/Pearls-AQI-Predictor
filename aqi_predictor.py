def run_shap_analysis(
    model,
    model_name,
    sample_data
):

    if model is None:

        print(
            f"⚠ Skipping {model_name}: model unavailable"
        )

        return None


    if not SHAP_AVAILABLE:

        print(
            f"⚠ Skipping {model_name}: SHAP unavailable"
        )

        return None


    print(
        f"\nRunning SHAP for {model_name}..."
    )


    try:

        explainer = shap.TreeExplainer(
            model
        )


        shap_values = explainer.shap_values(
            sample_data
        )


        # Some SHAP/model combinations return lists

        if isinstance(
            shap_values,
            list
        ):

            shap_values_plot = shap_values[0]

        else:

            shap_values_plot = shap_values


        # SHAP summary plot

        plt.figure(
            figsize=(12, 8)
        )

        shap.summary_plot(

            shap_values_plot,

            sample_data,

            show=False

        )

        plt.title(
            f"SHAP Feature Importance — {model_name}"
        )

        plt.tight_layout()

        safe_name = (
            model_name
            .lower()
            .replace(" ", "_")
            .replace("-", "")
        )


        plot_path = os.path.join(

            SHAP_DIR,

            f"shap_summary_{safe_name}.png"

        )


        plt.savefig(
            plot_path,
            dpi=150,
            bbox_inches="tight"
        )

        plt.show()


        # Mean absolute SHAP importance

        mean_abs_shap = np.abs(
            shap_values_plot
        ).mean(
            axis=0
        )


        importance_df = pd.DataFrame({

            "feature": sample_data.columns,

            "mean_abs_shap": mean_abs_shap

        })


        importance_df = (
            importance_df
            .sort_values(
                "mean_abs_shap",
                ascending=False
            )
            .reset_index(
                drop=True
            )
        )


        csv_path = os.path.join(

            SHAP_DIR,

            f"shap_importance_{safe_name}.csv"

        )


        importance_df.to_csv(
            csv_path,
            index=False
        )


        print(
            f"✓ SHAP plot saved: {plot_path}"
        )

        print(
            f"✓ SHAP importance saved: {csv_path}"
        )


        print(
            "\nTop 10 important features:"
        )

        print(
            importance_df.head(10)
        )


        return importance_df


    except Exception as e:

        print(
            f"⚠ SHAP failed for {model_name}"
        )

        print(
            "Reason:",
            e
        )

        return None


