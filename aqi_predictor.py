def create_features(data):

    """
    Convert incoming JSON data into the feature vector
    expected by the trained ML models.
    """

    feature_data = {}

    for feature in FEATURES:

        if feature in data:

            feature_data[
                feature
            ] = safe_float(
                data[feature]
            )

        else:

            feature_data[
                feature
            ] = 0.0


    feature_df = pd.DataFrame(
        [feature_data],
        columns=FEATURES
    )


    return feature_df


